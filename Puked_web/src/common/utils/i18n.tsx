interface I18nContextType {
  t: (key: keyof typeof translations['zh']) => string;
  lang: Language;
  setLang: (lang: Language) => void;
}

const I18nContext = createContext<I18nContextType | undefined>(undefined);

export const I18nProvider = ({ children }: { children: ReactNode }) => {
  const [lang, setLang] = useState<Language>(() => {
    const saved = localStorage.getItem('puked_lang');
    return (saved as Language) || (navigator.language.startsWith('zh') ? 'zh' : 'en');
  });

  const t = (key: keyof typeof translations['zh']) => {
    return translations[lang][key] || key;
  };

  const handleSetLang = (newLang: Language) => {
    setLang(newLang);
    localStorage.setItem('puked_lang', newLang);
  };

  return (
    <I18nContext.Provider value={{ t, lang, setLang: handleSetLang }}>
      {children}
    </I18nContext.Provider>
  );
};

export const useI18n = () => {
  const context = useContext(I18nContext);
  if (!context) {
    // 在开发环境下的热更新过程中，Context 可能会短暂丢失
    // 提供降级方案，避免应用崩溃
    console.warn('useI18n called outside I18nProvider, using fallback');
    return {
      t: (key: keyof typeof translations['zh']) => key,
      lang: 'zh' as Language,
      setLang: () => { }
    };
  }
  return context;
};
